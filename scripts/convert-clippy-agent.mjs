// Usage: node scripts/convert-clippy-agent.mjs <clippy agent.js> <clippy sounds-mp3.js>
import { readFileSync, writeFileSync } from "node:fs";

const [agentPath, soundsPath] = process.argv.slice(2);
if (!agentPath || !soundsPath) {
  console.error("Usage: node scripts/convert-clippy-agent.mjs <agent.js> <sounds-mp3.js>");
  process.exit(1);
}

const extractObjectLiteral = (source) => source.slice(source.indexOf("{"), source.lastIndexOf("}") + 1);

const agent = JSON.parse(extractObjectLiteral(readFileSync(agentPath, "utf8")));
const sounds = JSON.parse(extractObjectLiteral(readFileSync(soundsPath, "utf8")).replaceAll("'", '"'));

const header = "// Generated by scripts/convert-clippy-agent.mjs from clippy.js (MIT). Do not edit.\n";

writeFileSync(
  "src/rover/data/agent.ts",
  `${header}import type { AgentData } from "../types";\n\nexport const roverAgent = ${JSON.stringify(agent)} satisfies AgentData;\n`,
);
writeFileSync(
  "src/rover/data/sounds.ts",
  `${header}export const roverSounds: Readonly<Record<string, string>> = ${JSON.stringify(sounds)};\n`,
);

console.log(`Converted ${Object.keys(agent.animations).length} animations and ${Object.keys(sounds).length} sounds.`);
